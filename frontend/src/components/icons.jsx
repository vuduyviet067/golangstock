// Inline SVG icons for the app shell. No icon library is installed, and a few
// stroke icons do not justify one. Every icon is decorative (aria-hidden): the
// control that holds it carries the accessible name.

function Icon({ children, size = 20, className = '' }) {
  return (
    <svg
      className={`icon ${className}`.trim()}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.8"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  )
}

